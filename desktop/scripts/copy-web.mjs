// Copies the shared web app (../web) into the desktop shell, the same way mobile/scripts/copy-web.mjs
// does for Android. The copy is what the Windows and Linux apps are packed with.
//
//   node scripts/copy-web.mjs                 -> app-web/   production build. Refused unless
//                                                         QRQUICK_ALLOW_PRODUCTION_BUILD=1 is set by the owner.
//   node scripts/copy-web.mjs --staging-test  -> test-web/  TEST ONLY, staging project, never packed
//   node scripts/copy-web.mjs --staging-test --package
//                                             -> app-web/   TEST ONLY, staging project, packed as the TEST app
//
// Production build: the configuration is read from web/config.js and checked: the production Supabase
// project, a publishable key, the public address for QR codes and sign-in links, and ownerApp forced on.
// Refused: any secret key, any JWT, and the staging project inside the production build.
//
// Test copy: STAGING_SUPABASE_URL and STAGING_PUBLISHABLE_KEY must name the staging project. It refuses the
// production project. Its output folder is not referenced by electron-builder.
import { cp, mkdir, readFile, rm, writeFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const desktop = path.resolve(here, '..');
const source = path.resolve(desktop, '../web');
const APP_FILES = ['index.html', 'styles.css', 'config.js', 'manifest.webmanifest', 'icons', 'src'];

const PRODUCTION_REF = 'qvnwqrevgyootaaunrto';
const STAGING_REF = 'nbzojqlqkrydcjtogwrb';
const PRODUCTION_PUBLIC_URL = 'https://joyyxh.github.io/Ps-qr/';
const SECRET_PATTERNS = [/sb_secret_/, /eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}/];

const stagingTest = process.argv.includes('--staging-test');
const packageTest = process.argv.includes('--package');
if (packageTest && !stagingTest) fail('--package is only for the staging TEST build (--staging-test --package)');
if (!stagingTest && process.env.QRQUICK_ALLOW_PRODUCTION_BUILD !== '1') {
  fail(
    'this would build the production project, which does not have username sign-in yet ' +
      '(migrations 0021 and 0022 and the owner-auth function are on staging only). ' +
      'For a test build use --staging-test. A production build needs the owner\'s approval and QRQUICK_ALLOW_PRODUCTION_BUILD=1.'
  );
}
const target = path.join(desktop, stagingTest && !packageTest ? 'test-web' : 'app-web');

function fail(message) {
  console.error(`refused: ${message}`);
  process.exit(2);
}

// web/config.js is a classic script that sets window.PRINTNEST_CONFIG. Evaluate it in a sandbox object.
function readConfig(text) {
  const sandbox = {};
  new Function('window', text)(sandbox);
  if (!sandbox.PRINTNEST_CONFIG) fail('web/config.js does not set window.PRINTNEST_CONFIG');
  return sandbox.PRINTNEST_CONFIG;
}

let config = readConfig(await readFile(path.join(source, 'config.js'), 'utf8'));

if (stagingTest) {
  const url = (process.env.STAGING_SUPABASE_URL ?? '').trim();
  const key = (process.env.STAGING_PUBLISHABLE_KEY ?? '').trim();
  if (!new RegExp(`^https://${STAGING_REF}\\.supabase\\.co$`).test(url)) {
    fail(`STAGING_SUPABASE_URL must be https://${STAGING_REF}.supabase.co for the test copy`);
  }
  if (!key.startsWith('sb_publishable_')) fail('STAGING_PUBLISHABLE_KEY must be a publishable key (sb_publishable_...)');
  config = { ...config, supabaseUrl: url, publishableKey: key, ownerApp: true };
} else {
  if (config.supabaseUrl !== `https://${PRODUCTION_REF}.supabase.co`) {
    fail(`web/config.js must point at the production project ${PRODUCTION_REF}`);
  }
  if (!String(config.publishableKey || '').startsWith('sb_publishable_')) {
    fail('web/config.js must hold the publishable key of the production project');
  }
  if (config.publicBaseUrl !== PRODUCTION_PUBLIC_URL || config.authRedirectUrl !== PRODUCTION_PUBLIC_URL) {
    fail(`web/config.js publicBaseUrl and authRedirectUrl must be ${PRODUCTION_PUBLIC_URL}`);
  }
  config = { ...config, ownerApp: true };
}

const configText =
  (stagingTest
    ? '// TEST BUILD ONLY: this app talks to the qrquick-staging project. Generated by desktop/scripts/copy-web.mjs --staging-test.\n'
    : '// Generated by desktop/scripts/copy-web.mjs from web/config.js. Browser-safe values only.\n') +
  `window.PRINTNEST_CONFIG = ${JSON.stringify(config, null, 2)};\n`;

if (!stagingTest && configText.includes(STAGING_REF)) fail('the staging project must not appear in the production build');

await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
for (const name of APP_FILES) {
  await cp(path.join(source, name), path.join(target, name), { recursive: true });
}
await writeFile(path.join(target, 'config.js'), configText);

// Scan every copied file for secret keys before anything is packed.
async function scan(dir) {
  for (const entry of await readdir(dir)) {
    const full = path.join(dir, entry);
    if ((await stat(full)).isDirectory()) {
      await scan(full);
      continue;
    }
    const text = await readFile(full, 'utf8').catch(() => '');
    for (const pattern of SECRET_PATTERNS) {
      if (pattern.test(text)) fail(`a secret-looking value was found in ${path.relative(desktop, full)}`);
    }
  }
}
await scan(target);

console.log(
  `Copied ${APP_FILES.length} items from web/ into ${path.relative(desktop, target)}/ ` +
    `(Supabase project ${stagingTest ? STAGING_REF + ' (staging test copy)' : PRODUCTION_REF}, ` +
    `ownerApp true, QR address ${config.publicBaseUrl}).`
);
