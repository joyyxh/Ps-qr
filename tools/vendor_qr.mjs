// Converts the QR code encoder into one browser ES module, so the web page can make
// QR codes without a CDN. The encoder is the MIT-licensed "QRCode for JavaScript" by
// Kazuhiko Arase, as packaged in the vendor folder of qrcode-terminal.
//
// Run once (the output is committed, so the page does not need this script):
//   node tools/vendor_qr.mjs <folder that holds QRMode.js, QRUtil.js, ... index.js>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const from = process.argv[2];
if (!from) {
  console.error('Usage: node tools/vendor_qr.mjs <folder with the QRCode .js files>');
  process.exit(1);
}

// A file is evaluated after the files it requires.
const ORDER = [
  'QRMode',
  'QRErrorCorrectLevel',
  'QRMaskPattern',
  'QRMath',
  'QRBitBuffer',
  'QR8bitByte',
  'QRPolynomial',
  'QRRSBlock',
  'QRUtil',
  'index',
];

let out = `// QR code encoder as an ES module.
// Vendored from "QRCode for JavaScript" by Kazuhiko Arase (MIT licence, see LICENSE.txt
// in this folder). Generated by tools/vendor_qr.mjs. Do not edit by hand.
// "QR Code" is a registered trademark of DENSO WAVE INCORPORATED.

const __REG = {};
const __require = (name) => {
  const key = name.replace(/^\\.\\//, '');
  if (!(key in __REG)) throw new Error('QR module used before it loaded: ' + name);
  return __REG[key];
};
`;

for (const name of ORDER) {
  const code = readFileSync(join(from, `${name}.js`), 'utf8');
  out += `
__REG['${name}'] = (function () {
var module = { exports: {} };
var exports = module.exports;
var require = __require;
${code}
return module.exports;
})();
`;
}

out += `
export const QRCode = __REG['index'];
export const QRErrorCorrectLevel = __REG['QRErrorCorrectLevel'];
`;

writeFileSync(new URL('../web/src/vendor/qrcode/qrcode.js', import.meta.url), out);
console.log(`wrote web/src/vendor/qrcode/qrcode.js (${out.length} bytes)`);
