// Copies the web app from ../web into ./www, which Capacitor packs into the APK.
//
// Two modes:
//   node scripts/copy-web.mjs --staging-test
//     TEST BUILD ONLY. www/config.js points at the qrquick-staging project, with the publishable key
//     from STAGING_PUBLISHABLE_KEY. STAGING_SUPABASE_URL must be https://nbzojqlqkrydcjtogwrb.supabase.co.
//     The copy is scanned, and the build stops if the production project reference is in it.
//   node scripts/copy-web.mjs
//     The production project. Refused unless QRQUICK_ALLOW_PRODUCTION_BUILD=1 is set by the owner: the
//     production project does not have username sign-in yet (migrations 0021 and 0022 and the owner-auth
//     function are on staging only).
//
// Only the files the app needs are copied (no tests, no service worker, no build tools). The customer page
// address for QR codes is written into www/config.js from PRINTNEST_PUBLIC_URL.
//
//   PRINTNEST_PUBLIC_URL=https://your-printnest-site.example  node scripts/copy-web.mjs

import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../web');
const target = path.resolve(here, '../www');
const APP_FILES = ['index.html', 'styles.css', 'config.js', 'manifest.webmanifest', 'icons', 'src'];
const PUBLIC_URL_PATTERN = /^https:\/\/[a-z0-9.-]+(:\d{1,5})?(\/[A-Za-z0-9._~\/@-]*)?$/i;
const STAGING_URL = 'https://nbzojqlqkrydcjtogwrb.supabase.co';
const PRODUCTION_REF = 'qvnwqrevgyootaaunrto';

const stagingTest = process.argv.includes('--staging-test');
const publicUrl = (process.env.PRINTNEST_PUBLIC_URL ?? '').trim();
if (publicUrl && !PUBLIC_URL_PATTERN.test(publicUrl)) {
  console.error(`PRINTNEST_PUBLIC_URL must be a plain https:// address, for example https://printnest.example/ (got "${publicUrl}").`);
  process.exit(1);
}

if (!stagingTest && process.env.QRQUICK_ALLOW_PRODUCTION_BUILD !== '1') {
  console.error(
    'Refused: this would build the app for the production project, which does not have username sign-in yet ' +
      '(migrations 0021 and 0022 and the owner-auth function are on staging only). ' +
      'For a test build use --staging-test. A production build needs the owner\'s approval and QRQUICK_ALLOW_PRODUCTION_BUILD=1.'
  );
  process.exit(1);
}

let config;
if (stagingTest) {
  const url = (process.env.STAGING_SUPABASE_URL ?? '').trim();
  const key = (process.env.STAGING_PUBLISHABLE_KEY ?? '').trim();
  if (url !== STAGING_URL) {
    console.error(`--staging-test needs STAGING_SUPABASE_URL=${STAGING_URL} (got "${url}").`);
    process.exit(1);
  }
  if (!key.startsWith('sb_publishable_')) {
    console.error('--staging-test needs STAGING_PUBLISHABLE_KEY, a publishable key (sb_publishable_...). A secret key is never accepted.');
    process.exit(1);
  }
  config = `// TEST BUILD ONLY: this app talks to the qrquick-staging project. Generated by mobile/scripts/copy-web.mjs --staging-test.
// Browser-safe settings only. The publishable key is designed to be public.
window.PRINTNEST_CONFIG = {
  supabaseUrl: '${url}',
  publishableKey: '${key}',
  publicBaseUrl: '${publicUrl}',
  authRedirectUrl: '${publicUrl}',
  ownerApp: true,
};
`;
} else {
  config = await readFile(path.join(source, 'config.js'), 'utf8');
  if (publicUrl) {
    const replaced = config.replace(/publicBaseUrl:\s*'[^']*'/, `publicBaseUrl: '${publicUrl}'`);
    const withAuth = replaced.replace(/authRedirectUrl:\s*'[^']*'/, `authRedirectUrl: '${publicUrl}'`);
    if (!/publicBaseUrl:\s*'[^']*'/.test(config) || !/authRedirectUrl:\s*'[^']*'/.test(config)) {
      console.error('config.js has no publicBaseUrl/authRedirectUrl lines to set. Check web/config.js.');
      process.exit(1);
    }
    config = withAuth;
  } else {
    console.warn(
      'PRINTNEST_PUBLIC_URL is not set. QR codes made in the app would point at the app itself, ' +
        'and the app shows a warning until the address is set.'
    );
  }
  config = config.replace(/ownerApp:\s*(true|false)/, 'ownerApp: true');
  if (!/ownerApp:\s*true/.test(config)) {
    console.error('config.js has no ownerApp flag to configure the Android owner-only bundle.');
    process.exit(1);
  }
}

await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
for (const name of APP_FILES) {
  await cp(path.join(source, name), path.join(target, name), { recursive: true });
}
await writeFile(path.join(target, 'config.js'), config);

if (stagingTest) {
  // A test copy must not carry the production project. Any hit stops the build and removes the copy.
  const hits = [];
  for (const rel of await readdir(target, { recursive: true })) {
    const full = path.join(target, rel);
    if ((await stat(full)).isFile() && (await readFile(full)).includes(PRODUCTION_REF)) hits.push(rel);
  }
  if (hits.length > 0) {
    await rm(target, { recursive: true, force: true });
    console.error(`Refused: the test copy contains the production project reference in: ${hits.join(', ')}`);
    process.exit(1);
  }
}

const label = stagingTest ? 'TEST BUILD, qrquick-staging project' : 'production project';
console.log(`Copied ${APP_FILES.length} items from web/ into www/ (${label}) ${publicUrl ? `(QR address: ${publicUrl})` : '(no QR address set)'}`);
