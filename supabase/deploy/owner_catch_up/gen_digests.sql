-- GENERATOR. Run once, on a database at migration 0009. Never run it on the hosted project.
--   psql -X -At -d <database-at-0009> -f gen_digests.sql > digests.sql
--
-- Prints digests.sql: one row per public table with its row count and a digest of its rows, computed
-- over ONLY the columns that exist at 0009. The catch-up adds columns and tables; they are left out on
-- purpose. So an unchanged digest means the existing rows were not changed by the catch-up.
select '-- Read-only. GENERATED by gen_digests.sql from the 0009 column lists. Do not edit by hand.' || chr(10)
    || 'select t, n, d from (' || chr(10)
    || string_agg(
         format(
           'select %L::text as t, count(*) as n, md5(coalesce(string_agg(x, chr(10) order by x), %L)) as d from (select concat_ws(chr(31), %s) as x from public.%I) s',
           c.table_name, '', c.cols, c.table_name),
         chr(10) || 'union all' || chr(10)
         order by c.table_name)
    || chr(10) || ') z order by t;'
from (
  select t.table_name::text as table_name,
         string_agg(format('coalesce(%I::text, %L)', col.column_name, '~null~'), ', ' order by col.ordinal_position) as cols
  from information_schema.tables t
  join information_schema.columns col
    on col.table_schema = t.table_schema and col.table_name = t.table_name
  where t.table_schema = 'public' and t.table_type = 'BASE TABLE'
  group by t.table_name
) c;
