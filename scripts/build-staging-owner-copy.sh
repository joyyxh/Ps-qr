#!/usr/bin/env bash
# Builds a static copy of the owner app that points at the qrquick-staging Supabase project.
#
# Usage: scripts/build-staging-owner-copy.sh <output-dir> [public-app-url]
#   public-app-url  optional: where the copy will be hosted, for example https://owner-staging.example/.
#                   Leave it out to use the address of the page itself (the live config.js does the same).
# Environment (required):
#   STAGING_SUPABASE_URL      https://<staging-ref>.supabase.co
#   STAGING_PUBLISHABLE_KEY   sb_publishable_...
#
# The copy is web/ with one generated config.js (ownerApp: true). The repository's web/config.js is not
# changed, and the tests and package.json are left out. The script refuses anything that is not a
# publishable key, and it refuses the live project.
set -euo pipefail

if [ "$#" -lt 1 ]; then
  echo "usage: $0 <output-dir> [public-app-url]" >&2
  exit 2
fi
OUT="$1"
PUBLIC_URL="${2:-}"
HERE="$(cd "$(dirname "$0")" && pwd)"
WEB="$(cd "$HERE/../web" && pwd)"

: "${STAGING_SUPABASE_URL:?set STAGING_SUPABASE_URL to https://<staging-ref>.supabase.co}"
: "${STAGING_PUBLISHABLE_KEY:?set STAGING_PUBLISHABLE_KEY to the staging sb_publishable_ key}"

case "$STAGING_PUBLISHABLE_KEY" in
  sb_publishable_*) ;;
  *) echo "refused: the key must be a publishable key (sb_publishable_...)" >&2; exit 2 ;;
esac
if ! [[ "$STAGING_SUPABASE_URL" =~ ^https://[a-z0-9]+\.supabase\.co$ ]]; then
  echo "refused: STAGING_SUPABASE_URL must look like https://<ref>.supabase.co" >&2
  exit 2
fi
if [[ "$STAGING_SUPABASE_URL" == *qvnwqrevgyootaaunrto* ]]; then
  echo "refused: that URL is the live project, not staging" >&2
  exit 2
fi
if [ -n "$PUBLIC_URL" ] && ! [[ "$PUBLIC_URL" =~ ^https?://[^[:space:]\'\"]+$ ]]; then
  echo "refused: public-app-url must start with http:// or https:// and contain no quotes or spaces" >&2
  exit 2
fi

# STAGING_OWNER_ONLY=1 (default) builds the owner-only app, as the Android app is built.
# STAGING_OWNER_ONLY=0 builds the full website, with the customer pages and the owner area.
OWNER_ONLY="${STAGING_OWNER_ONLY:-1}"
case "$OWNER_ONLY" in
  1) OWNER_ONLY_JS=true; KIND="owner-only app" ;;
  0) OWNER_ONLY_JS=false; KIND="full website" ;;
  *) echo "refused: STAGING_OWNER_ONLY must be 1 or 0" >&2; exit 2 ;;
esac

rm -rf "$OUT"
mkdir -p "$OUT"
cp -R "$WEB"/. "$OUT"/
rm -rf "$OUT/tests" "$OUT/package.json"

cat > "$OUT/config.js" <<EOF
// Staging copy of the owner app, generated by scripts/build-staging-owner-copy.sh.
// Browser-safe settings only. The publishable key is designed to be public.
window.PRINTNEST_CONFIG = {
  supabaseUrl: '$STAGING_SUPABASE_URL',
  publishableKey: '$STAGING_PUBLISHABLE_KEY',
  publicBaseUrl: '$PUBLIC_URL',
  authRedirectUrl: '$PUBLIC_URL',
  ownerApp: $OWNER_ONLY_JS,
};
EOF

# The copy must not carry a service-role key or the live project. Any hit fails the build.
if grep -rIlE 'service_role|sb_secret_|qvnwqrevgyootaaunrto' "$OUT" >/dev/null; then
  echo "refused: the copy contains a service-role key or the live project reference:" >&2
  grep -rIlE 'service_role|sb_secret_|qvnwqrevgyootaaunrto' "$OUT" >&2
  rm -rf "$OUT"
  exit 1
fi

echo "built staging $KIND at $OUT (backend: $STAGING_SUPABASE_URL)"
